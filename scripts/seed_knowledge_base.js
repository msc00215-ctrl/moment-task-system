async function main() {
  const auth = new google.auth.GoogleAuth({ keyFile: KEY_FILE, scopes: ['https://www.googleapis.com/auth/spreadsheets'] });
  const sheets = google.sheets({ version: 'v4', auth });

  // 既存データを確認
  const cur = await sheets.spreadsheets.values.get({
    spreadsheetId: SS_MAIN, range: `'${SHEET}'!A1:D200`,
    valueRenderOption: 'FORMATTED_VALUE'
  });
  const existing = cur.data.values || [];
  const existingTexts = new Set(existing.map(r => r[2] || ''));
  console.log('既存行数:', existing.length);

  // 重複除外して新規行だけ追加
  const newRows = SEED_DATA
    .filter(([,content]) => !existingTexts.has(content))
    .map(([cat, content, src]) => [NOW, cat, content, src]);

  if (newRows.length === 0) {
    console.log('✅ 追加する新規データなし（すべて既存）');
    return;
  }

  await sheets.spreadsheets.values.append({
    spreadsheetId: SS_MAIN,
    range: `'${SHEET}'!A:D`,
    valueInputOption: 'USER_ENTERED',
    insertDataOption: 'INSERT_ROWS',
    requestBody: { values: newRows }
  });

  console.log(`✅ ${newRows.length}件 追加完了`);
  const cats = [...new Set(newRows.map(r => r[1]))];
  cats.forEach(c => {
    const n = newRows.filter(r => r[1] === c).length;
    console.log(`  ${c}: ${n}件`);
  });
}

main().catch(e => { console.error('❌', e.message); process.exit(1); });
